/**
 * return the appId from the mobile stores
 * @param storeName
 */
const getAppStoreId = (environment: Environment, storeName: 'ios' | 'android') => {
  const result = environment.settings.appStoreUrls.find((store) => store.name === storeName);

  if (!result || !result.appId) {
    return;
  }

  return result.appId;
};

/**
 * return domain of a url
 */
const getDomainFromUrl = (url: string): string | undefined => {
  if (!url) {
    return;
  }

  const regex = /(?:https?:\/\/)?(?:[^@\/\n]+@)?(?:www\.)?([^:\/\n]+)/i;
  const result = regex.exec(url);
  if (result !== null) {
    return result[0];
  }
  return;
};

/**
 * copy file and replace handlebar variables
 */
const handleBarGulpTask = (src, dest, config = siteConfig) => {
  return gulp.src(src).pipe($.compileHandlebars(config, handleBarSettings)).pipe(gulp.dest(dest));
};

/** minify file */
const minifyFileGulpTask = (src, dest, env = environment) => {
  env = env ? env : environment;
  const minifyEnabled = env.settings.environment !== 'dev';

  return gulp
    .src(src)
    .pipe(
      $.htmlmin({
        removeComments: minifyEnabled,
        collapseWhitespace: minifyEnabled,
        minifyJS: minifyEnabled,
        minifyCSS: minifyEnabled,
      }),
    )
    .pipe(gulp.dest(dest));
};

// general handlebar settings and helpers
const handleBarSettings = {
  compile: { noEscape: true },
  helpers: {
    cdn: (file) => {
      let filePathNew = file;

      // hash
      if (environment.settings.environment !== 'local') {
        const currentFile = fileHashes['hashes'].find((item) => item['path'] === file);

        if (currentFile) {
          filePathNew = currentFile.hashPath;
        }
      }

      // cdn
      if (environment.cdn.baseApiUrl !== '' && IS_MOBILE === 'false') {
        filePathNew = `${environment.cdn.baseApiUrl}${filePathNew}`;
      }

      return filePathNew;
    },
  },
};

