/**
 * generate a json file which contains the file hashes from all files in the src folder
 */
gulp.task('site.hashes.saveJsonFile', (done: any) => {
  // debug generated hashes
  // fs.writeFileSync('src/debug-hashes.json', JSON.stringify(fileHashes, null, 2));

  fs.writeFileSync(
    'src/hashes.json',
    (() => {
      if (environment.settings.environment === 'local') {
        return '{}';
      }
      const json = {};
      fileHashes.hashes.forEach((currentFile) => {
        json[currentFile.path] = currentFile.hash;
      });
      return `${JSON.stringify(json, null, 2)}\n`;
    })(),
  );

  done();
});

/**
 * rename all files in the hash folder and add hash to their path
 */
gulp.task('site.hashes.rename', (done: any) => {
  if (environment.settings.environment !== 'local') {
    fileHashes.hashes.forEach((currentFile) => {
      if (currentFile.rename) {
        fs.renameSync(path.join(fileHashes.assetFolder, currentFile.path), path.join(fileHashes.assetFolder, currentFile.hashPath));
      }
    });
  }

  done();
});

